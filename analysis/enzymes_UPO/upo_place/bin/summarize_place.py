#!/usr/bin/env python3
"""G1 summary of fungal PF01328 proteins across BFD, with clade calls from phylogenetic
placement (upo_place) instead of nearest-neighbour identity (upo_sites).

  summarize_place.py --table upo_place_bfd_all.tsv.zst --out G1_BFD_SUMMARY.md

Input is the merged table written by compare_bfd.py: every upo_sites column (residues in HspUPO
numbering, lineage) plus `place_*` columns. Sections follow the earlier nearest-neighbour report
(git history of G1_BFD_SUMMARY.md) so the two can be compared section by section; each section
that depends on the clade call reports the old call alongside where that is informative.
Standard library only.
"""
from __future__ import annotations

import argparse
import csv
import io
import subprocess
import sys
from collections import Counter, defaultdict

CLADES = ["Clade I", "Clade II", "Clade III", "Clade IV", "Clade V", "unassigned"]
# Observed peroxygenase range per clade in the 19-enzyme calibration set (CALIBRATION_MATRIX.md).
T1 = {"Clade I": "0-53, bimodal", "Clade II": "0", "Clade III": "0-3", "Clade IV": "0-5 (n=1)",
      "Clade V": "33-82", "unassigned": "n/a"}


def read_table(path):
    if path.endswith(".zst"):
        txt = subprocess.run(["zstd", "-dcq", path], capture_output=True, text=True,
                             check=True).stdout
        fh = io.StringIO(txt)
    else:
        fh = open(path, newline="")
    return list(csv.DictReader((l for l in fh if not l.startswith("#")), delimiter="\t"))


def old_clade(c):
    return "unassigned" if c in ("", "unassigned") else f"Clade {c}"


def pct(a, b):
    return f"{100 * a / b:.1f} %" if b else "-"


def conf_tier(r):
    c = r["place_our_clade"]
    if c != "unassigned":
        return "assigned, LWR >= 0.95" if float(r["place_our_lwr"]) >= 0.95 else \
            "assigned, LWR 0.5-0.95"
    if float(r["place_our_stem_lwr"]) >= 0.5:
        return "unassigned: on the stem of a clade"
    return "unassigned: outside Clades I-V"


def core(r):
    return (r.get("p39_Cys_proximal") == "C" and r.get("p109_E_of_EHD") == "E"
            and r.get("p111_D_of_EHD") == "D" and r.get("p180_Acid") == "E")


def build(rows, source):
    n = len(rows)
    out = []
    W = out.append
    W("# G1: fungal PF01328 diversity across BFD (placement clade calls)\n")
    W(f"Generated by `upo_place/bin/summarize_place.py` from `{source}`. **n = {n} proteins.**\n")
    W("Clade calls are by **phylogenetic placement** (epa-ng) on the 187-leaf reference tree "
      "(19 characterized enzymes + 168 curated HTPs from Zamocky et al. 2022); see "
      "`upo_place/README.md`. Leave-one-out over all 187 reference leaves: **184/187 correct** for "
      "Clades I-V, across identity strata from < 30 % to > 52.7 % to the nearest characterized "
      "enzyme. This replaces the nearest-neighbour report (same file, git history before "
      "2026-11-09), whose calls were validated only at >= 52.7 % identity (13 % of proteins).\n")
    n_out = len({r["place_fig1_clade"] for r in rows}
                - {"unassigned", "Basidiomycetous 3rd (Family II, long)",
                   "Ascomycetous 2nd (Family I, short)"})
    W("A protein is `unassigned` when its placements do not fall inside Clades I-V with "
      f"accumulated LWR >= 0.5. That is a result: {n_out} of Zamocky's Figure 1 clades that "
      "received BFD proteins lie outside our clades (section 2b).\n")

    W("## 1. Call confidence\n")
    tc = Counter(conf_tier(r) for r in rows)
    W("| call | n | % |")
    W("|---|---|---|")
    for k in ("assigned, LWR >= 0.95", "assigned, LWR 0.5-0.95",
              "unassigned: on the stem of a clade", "unassigned: outside Clades I-V"):
        W(f"| {k} | {tc[k]} | {pct(tc[k], n)} |")
    lp = sum(1 for r in rows if r["place_flags"])
    W(f"\n`long_pendant` (best placement farther from every reference than any correct "
      f"leave-one-out call): **{lp}** proteins ({pct(lp, n)}); their calls are kept and flagged.\n")

    W("## 2. Clade counts\n")
    new = Counter(r["place_our_clade"] for r in rows)
    old = Counter(old_clade(r["clade"]) for r in rows)
    oldv = Counter(old_clade(r["clade"]) for r in rows
                   if r["clade_confidence"].startswith("validated"))
    W("| clade | placement | old: all calls | old: validated range | in-sample T1 (n=19) |")
    W("|---|---|---|---|---|")
    for c in CLADES:
        W(f"| {c} | {new[c]} | {old[c]} | {oldv[c]} | {T1[c]} |")
    W("\nClade IV is no longer a one-reference clade in the tree: it has 20 reference leaves "
      "(MphUPO + 19 curated ascomycete HTPs, UFBoot 96). Its activity calibration is still "
      "MphUPO alone, so the T1 column for IV remains n = 1.\n")

    W("### 2a. Old call -> placement\n")
    mv = defaultdict(Counter)
    for r in rows:
        t = "validated" if r["clade_confidence"].startswith("validated") else (
            "below floor" if r["clade_confidence"].startswith("below") else "extrapolated")
        mv[f"{old_clade(r['clade'])} ({t})"][r["place_our_clade"]] += 1
    W("| old call (tier) | " + " | ".join(CLADES) + " | total |")
    W("|---" * (len(CLADES) + 2) + "|")
    for k in sorted(mv):
        W(f"| {k} | " + " | ".join(str(mv[k][c]) for c in CLADES)
          + f" | {sum(mv[k].values())} |")
    conf = []
    for c in CLADES[:-1]:
        k = f"{c} (validated)"
        tot = sum(mv[k].values())
        if tot:
            conf.append(f"{c} {mv[k][c]}/{tot}")
    ext = []
    for c in CLADES[:-1]:
        k = f"{c} (extrapolated)"
        tot = sum(mv[k].values())
        if tot:
            ext.append(f"{c} {mv[k][c]}/{tot}")
    iii = [r for r in rows if r["clade"] == "III"
           and r["clade_confidence"].startswith("validated")
           and r["place_our_clade"] == "unassigned"]
    iii_stem = sum(1 for r in iii if float(r["place_our_stem_lwr"]) >= 0.5)
    W("\nOld validated-range calls confirmed by placement: " + "; ".join(conf) + ". "
      "Old extrapolated calls confirmed: " + "; ".join(ext) + ". "
      f"Of the {len(iii)} unconfirmed validated Clade III calls, {iii_stem} sit on the stem of "
      "the 3-leaf reference Clade III (close relatives of MroUPO/MorUPO branching just outside "
      "it).\n")

    W("### 2b. Zamocky Figure 1 clades\n")
    f1 = Counter(r["place_fig1_clade"] for r in rows)
    W("| Figure 1 clade | n | relation to Clades I-V |")
    W("|---|---|---|")
    rel = {"Basidiomycetous 3rd (Family II, long)": "= Clade I",
           "Ascomycetous 2nd (Family I, short)": "contains Clades III, IV, V"}
    for k, v in f1.most_common():
        W(f"| {k} | {v} | {rel.get(k, 'outside Clades I-V' if k != 'unassigned' else '')} |")
    W("")

    W("## 3. Pocket score (0-5) by clade\n")
    ps = defaultdict(list)
    for r in rows:
        ps[r["place_our_clade"]].append(int(r["pocket_score"]))
    W("| clade | n | mean | 5/5 | 0/5 |")
    W("|---|---|---|---|---|")
    for c in CLADES:
        v = ps[c]
        if v:
            W(f"| {c} | {len(v)} | {sum(v) / len(v):.2f} | {v.count(5)} | {v.count(0)} |")
    W("")

    W("## 4. Clade distribution by lineage\n")
    lg, lgn = defaultdict(Counter), Counter()
    for r in rows:
        g = r.get("LINEAGE_GROUP") or "?"
        lg[g][r["place_our_clade"]] += 1
        lgn[g] += 1
    W("| lineage | n | " + " | ".join(CLADES) + " |")
    W("|---" * (len(CLADES) + 2) + "|")
    for g in sorted(lgn, key=lambda k: -lgn[k]):
        W(f"| {g} | {lgn[g]} | " + " | ".join(str(lg[g][c]) for c in CLADES) + " |")
    W("")
    W("### 4a. Lineage x Figure 1 clade (lineages with >= 100 proteins)\n")
    fcl = [k for k, _ in f1.most_common()]
    lf = defaultdict(Counter)
    for r in rows:
        lf[r.get("LINEAGE_GROUP") or "?"][r["place_fig1_clade"]] += 1
    short = {k: k.split(" (")[0] for k in fcl}
    W("| lineage | n | " + " | ".join(short[k] for k in fcl) + " |")
    W("|---" * (len(fcl) + 2) + "|")
    for g in sorted(lgn, key=lambda k: -lgn[k]):
        if lgn[g] >= 100:
            W(f"| {g} | {lgn[g]} | " + " | ".join(str(lf[g][k]) for k in fcl) + " |")
    W("")

    W("## 5. Catalytic machinery\n")
    ok = sum(1 for r in rows if r["catalytic_ok"] == "yes")
    cys = sum(1 for r in rows if r.get("p39_Cys_proximal") == "C")
    base = Counter(r.get("p110_Base_EHD", "-") for r in rows)
    W(f"- Full catalytic set intact (Cys39, Glu109, Asp111, Glu180): **{ok}/{n} ({pct(ok, n)})**")
    W(f"- Proximal Cys39 present: **{cys}/{n} ({pct(cys, n)})**")
    W("- Residue at position 110 (His in short UPOs, Gly in long): "
      + ", ".join(f"{k}={v}" for k, v in base.most_common(6)))
    W("\nThese residue counts do not depend on the clade caller and are unchanged.\n")

    W("## 6. Glu180 and the catalytic-core filter\n")
    W("The 2025 paper reports Glu180 (HspUPO numbering) in all 19 characterized UPOs. Placement "
      "shows that its absence is **lineage-structured**, so it cannot be read as a per-protein "
      "'not a UPO' test without knowing the lineage.\n")
    g = defaultdict(Counter)
    for r in rows:
        g[r["place_our_clade"]][r.get("p180_Acid") == "E"] += 1
    W("| clade | n | Glu180 |")
    W("|---|---|---|")
    for c in CLADES:
        t = g[c][True] + g[c][False]
        if t:
            W(f"| {c} | {t} | {pct(g[c][True], t)} |")
    W("\n**Clade I by phylum** (Clade I = Zamocky Family II, long):\n")
    gp = defaultdict(Counter)
    res = defaultdict(Counter)
    for r in rows:
        if r["place_our_clade"] == "Clade I":
            ph = r.get("PHYLUM") or "?"
            gp[ph][r.get("p180_Acid") == "E"] += 1
            res[ph][r.get("p180_Acid", "-")] += 1
    W("| phylum | n | Glu180 | most common residues at 180 |")
    W("|---|---|---|---|")
    for ph in sorted(gp, key=lambda k: -(gp[k][True] + gp[k][False])):
        t = gp[ph][True] + gp[ph][False]
        W(f"| {ph} | {t} | {pct(gp[ph][True], t)} | "
          + ", ".join(f"{k} {v}" for k, v in res[ph].most_common(4)) + " |")
    oi = [r for r in rows if r["clade"] == "I"]
    oi_glu = sum(1 for r in oi if r.get("p180_Acid") == "E")
    oi_f2 = sum(1 for r in oi
                if r["place_fig1_clade"] == "Basidiomycetous 3rd (Family II, long)")
    W(f"\nThe earlier report read the {pct(oi_glu, len(oi))} Glu180 rate of old Clade I calls "
      f"as the low-identity bin absorbing non-UPOs. Placement puts {pct(oi_f2, len(oi))} of "
      "those proteins inside Family II, and the "
      "non-Glu residue (mostly Ala) is concentrated in **ascomycete long UPOs**, matching all 13 "
      "curated ascomycete Family II sequences in Zamocky et al. 2022 (A/S/T at this position). The "
      "five characterized Clade I enzymes are basidiomycete and carry Glu. So the low rate is a "
      "property of ascomycete long UPOs, not evidence of contamination. **Open:** whether they "
      "lack the acid-base Glu or carry it at a position that does not align to HspUPO 180 "
      "(test against a structure-based alignment of an ascomycete long UPO).\n")
    W("**Basidiomycetous 1st** (an early lineage outside Clades I-V) lacks Glu180 almost "
      "entirely: "
      + (lambda c: f"{c[True]}/{c[True] + c[False]} carry Glu")(Counter(
          r.get("p180_Acid") == "E" for r in rows
          if r["place_fig1_clade"] == "Basidiomycetous 1st"))
      + "; all 34 curated members carry Asn or Ser.\n")

    W("### Catalytic core set\n")
    cs = [r for r in rows if core(r)]
    W(f"Requiring Cys39 + Glu109 + Asp111 + Glu180: **{len(cs)}/{n} ({pct(len(cs), n)})** "
      "proteins (unchanged; the filter does not use the clade).\n")
    cc = Counter(r["place_our_clade"] for r in cs)
    cf = Counter(r["place_fig1_clade"] for r in cs)
    W("| clade | catalytic core | all proteins |")
    W("|---|---|---|")
    for c in CLADES:
        W(f"| {c} | {cc[c]} | {new[c]} |")
    W("\n| Figure 1 clade | catalytic core |")
    W("|---|---|")
    for k, v in cf.most_common():
        W(f"| {k} | {v} |")
    W("\nThe core set is a **conservative** UPO set: by construction it excludes nearly all "
      "ascomycete Clade I (long) proteins and nearly all Basidiomycetous 1st proteins, because of the "
      "Glu180 requirement. Whether those lineages are functional UPOs is the open question above, "
      "not something the filter settles. Use the core set where a strict UPO definition is "
      "needed; report the excluded lineages separately rather than as non-UPOs.\n")

    W("## 7. Copy number per genome\n")
    per = Counter(r["protein_id"].split("_")[0] for r in rows)
    sp = {r["protein_id"].split("_")[0]: r.get("SPECIES", "?") for r in rows}
    top = per.most_common(10)
    W(f"- genomes with at least one PF01328: **{len(per)}**")
    W(f"- maximum copies in one genome: **{top[0][1]}**")
    W("\n| genome | copies | species |")
    W("|---|---|---|")
    for lt, k in top:
        W(f"| {lt} | {k} | *{sp.get(lt, '?')}* |")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, help="merged table from compare_bfd.py")
    ap.add_argument("--source-label", default=None, help="path to print in the report header")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    rows = read_table(a.table)
    if not rows:
        sys.exit(f"no rows in {a.table}")
    open(a.out, "w").write(build(rows, a.source_label or a.table))
    print(f"wrote {a.out} ({len(rows)} proteins)", file=sys.stderr)


if __name__ == "__main__":
    main()
