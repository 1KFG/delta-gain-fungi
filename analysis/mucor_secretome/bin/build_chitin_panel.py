#!/usr/bin/env python3
"""Pick the chitin-axis chains for the AF3 screen, and the controls that calibrate it.

  build_chitin_panel.py --fold-calls fold_calls.tsv --folds-faa to_fold.faa \
      --plant-panel plant_panel/panel.tsv --plant-faa plant_panel/panel.faa \
      --out chitin_panel/

Fungal side: every candidate whose predicted fold was ASSIGNED (TM >= 0.5, pLDDT >= 70) to a
LysM domain, a chitin/peptidoglycan deacetylase, a cerato-platanin or a chitinase. These are
the proteins that would act on the chitin signal - deacetylases convert chitin to chitosan that
LysM receptors bind poorly, LysM proteins and cerato-platanins bind the oligomers directly.

Host side: the LysM receptor ectodomains of both Marchantia species, plus their chitinases as
the enzymes that generate the oligomer in the first place.

Controls are not optional here. iPTM has no universal threshold and the AlphaFold-Multimer
figures were calibrated on large complexes, not small cysteine-rich effectors. Two positives
with solved structures bracket the question, and two negatives say what a non-interaction
scores in the same run:
  4EBZ  AtCERK1 LysM ectodomain with chito-oligosaccharide - a solved protein/ligand complex of
        exactly the kind this screen predicts
  6Q76  AVR-PikD effector with the Pikp-1 HMA domain - a solved small fungal effector bound to
        its plant target, the closest published analogue of the protein/protein half
  negative pairings are generated by crossing a control effector with an unrelated host chain.
Control sequences are fetched from RCSB by the job script, since the construct in the solved
structure is the one worth reproducing. Standard library only.
"""
from __future__ import annotations

import argparse
import csv
import os
import re
import sys

FUNGAL_FOLDS = [
    ("lysm", re.compile(r"lysm", re.I)),
    ("deacetylase", re.compile(r"deacetylase", re.I)),
    ("cerato_platanin", re.compile(r"cerato", re.I)),
    ("chitinase", re.compile(r"chitin.*(ase|domain)", re.I)),
]
# Tier A, the default: the LysM receptors are what perceive the chitin signal, and they are the
# chains the hypothesis names. Tier B (--host-classes lysm_receptor,chitinase,chitin_binding)
# adds the host chitinases, which are legitimate effector targets - LysM effectors and AVR4-type
# proteins protect the fungal wall from them - but crossing all of them with all the fungal
# chains is 784 predictions, and a screen is worth widening only once its controls have said
# what a score means.
HOST_CLASSES = {"lysm_receptor"}


def fungal_hits(rows, min_plddt=70.0):
    """-> [(protein_id, fold_label)] for assigned calls whose fold is on the chitin axis."""
    out = []
    for r in rows:
        if r.get("fold_call") != "assigned":
            continue
        try:
            if float(r.get("plddt") or 0) < min_plddt:
                continue
        except ValueError:
            continue
        desc = r.get("best_desc", "")
        for label, pat in FUNGAL_FOLDS:
            if pat.search(desc):
                out.append((r["protein_id"], label))
                break
    return out


def host_hits(rows, classes=HOST_CLASSES, min_len=40, max_len=400):
    """-> [(protein_id, class, species)] for panel constructs in the chitin-facing classes.

    The ectodomain construct is what the panel already holds; anything longer than max_len is a
    whole receptor that slipped through and would dominate a prediction."""
    out = []
    for r in rows:
        if r.get("class") not in classes:
            continue
        try:
            n = int(r.get("construct_len") or 0)
        except ValueError:
            continue
        if not (min_len <= n <= max_len):
            continue
        out.append((r["protein_id"], r["class"], r.get("species", "")))
    return out


def read_tsv(path):
    with open(path) as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def read_fasta(path):
    name, buf = None, []
    with open(path) as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if name:
                    yield name, "".join(buf)
                name, buf = line[1:].split()[0], []
            elif line:
                buf.append(line.strip())
    if name:
        yield name, "".join(buf)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--fold-calls", required=True)
    ap.add_argument("--folds-faa", required=True)
    ap.add_argument("--plant-panel", required=True)
    ap.add_argument("--plant-faa", required=True)
    ap.add_argument("--min-plddt", type=float, default=70.0)
    ap.add_argument("--host-classes", default=",".join(sorted(HOST_CLASSES)),
                    help="comma-separated panel classes to take as host chains")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)

    fung = fungal_hits(read_tsv(a.fold_calls), a.min_plddt)
    host = host_hits(read_tsv(a.plant_panel),
                     classes={c for c in a.host_classes.split(",") if c})
    fseq = dict(read_fasta(a.folds_faa))
    # the plant panel FASTA names constructs "<id>|<class>|<construct>"
    pseq = {h.split("|")[0]: s for h, s in read_fasta(a.plant_faa)}

    fung = [(p, lab) for p, lab in fung if p in fseq]
    host = [(p, c, sp) for p, c, sp in host if p in pseq]

    with open(os.path.join(a.out, "fungal.txt"), "w") as fh:
        fh.write("".join(f"{p}\n" for p, _ in fung))
    with open(os.path.join(a.out, "host.txt"), "w") as fh:
        fh.write("".join(f"{p}\n" for p, _, _ in host))
    with open(os.path.join(a.out, "panel.tsv"), "w", newline="") as fh:
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["protein_id", "side", "label", "species", "length"])
        for p, lab in fung:
            w.writerow([p, "fungal", lab, "", len(fseq[p])])
        for p, c, sp in host:
            w.writerow([p, "host", c, sp, len(pseq[p])])
    with open(os.path.join(a.out, "panel.faa"), "w") as fh:
        for p, _ in fung:
            fh.write(f">{p}\n{fseq[p]}\n")
        for p, _c, _s in host:
            fh.write(f">{p}\n{pseq[p]}\n")

    print(f"fungal {len(fung)} ({sorted({l for _, l in fung})}), host {len(host)} "
          f"({sorted({c for _, c, _ in host})}) -> {len(fung) * len(host)} pairs", file=sys.stderr)
    for sp in sorted({s for _, _, s in host}):
        print(f"  host {sp}: {sum(1 for _, _, s in host if s == sp)}", file=sys.stderr)
    return 0 if fung and host else 1


if __name__ == "__main__":
    sys.exit(main())
